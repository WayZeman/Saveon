export function translate(lang: Lang, key: string, ...args: string[]): string {
  const text = translations.uk[key] ?? key;
  return args.reduce((s, a, i) => s.replace(`{${i}}`, a), text);
}

export function getStoredLang(): Lang {
  return "uk";
}

